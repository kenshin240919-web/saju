  function calcYearPillar(year, month, day) {
    // 입춘(2월 4일경) 전이면 전년도 기준
    let adjYear = year;
    if (month < 2 || (month === 2 && day < 4)) {
      adjYear = year - 1;
    }
    const ganIdx = (adjYear - 4) % 10;
    const jiIdx = (adjYear - 4) % 12;
    return { gan: 천간[ganIdx], ji: 지지[jiIdx], ganIdx, jiIdx };
  }

  // 월주 계산 (절기 기반)
  function calcMonthPillar(year, month, day, yearGan) {
    // 절기 기반 월 결정
    let monthJiIdx;

    // 절기 기반으로 월지 결정
    if (month === 1 && day < 6) { monthJiIdx = 1; } // 축 (전년 12월주)
    else if (month === 1 || (month === 2 && day < 4)) { monthJiIdx = 1; } // 축
    else if (month === 2 || (month === 3 && day < 6)) { monthJiIdx = 2; } // 인
    else if (month === 3 || (month === 4 && day < 5)) { monthJiIdx = 3; } // 묘
    else if (month === 4 || (month === 5 && day < 6)) { monthJiIdx = 4; } // 진
    else if (month === 5 || (month === 6 && day < 6)) { monthJiIdx = 5; } // 사
    else if (month === 6 || (month === 7 && day < 7)) { monthJiIdx = 6; } // 오
    else if (month === 7 || (month === 8 && day < 8)) { monthJiIdx = 7; } // 미
    else if (month === 8 || (month === 9 && day < 8)) { monthJiIdx = 8; } // 신
    else if (month === 9 || (month === 10 && day < 8)) { monthJiIdx = 9; } // 유
    else if (month === 10 || (month === 11 && day < 7)) { monthJiIdx = 10; } // 술
    else if (month === 11 || (month === 12 && day < 7)) { monthJiIdx = 11; } // 해
    else { monthJiIdx = 0; } // 자

    // 월간 계산: 연간에 따라 정해진 시작점 + (월지인덱스 - 2) offset
    const startGanIdx = 월간시작[yearGan];
    let offset = monthJiIdx - 2;
    if (offset < 0) offset += 12;
    const monthGanIdx = (startGanIdx + offset) % 10;

    return { gan: 천간[monthGanIdx], ji: 지지[monthJiIdx], ganIdx: monthGanIdx, jiIdx: monthJiIdx };
  }

  // 일주 계산
  function calcDayPillar(year, month, day) {
    // 기준: 2000년 1월 7일 = 갑자일 (JDN 상 보정)
    const baseJDN = getJulianDayNumber(2000, 1, 7); // 갑자
    const targetJDN = getJulianDayNumber(year, month, day);
    let diff = targetJDN - baseJDN;
    let ganIdx = ((diff % 10) + 10) % 10;
    let jiIdx = ((diff % 12) + 12) % 12;
    return { gan: 천간[ganIdx], ji: 지지[jiIdx], ganIdx, jiIdx };
  }

  // 시주 계산
  function calcHourPillar(hour, dayGan) {
    const jiIdx = getHourJiIdx(hour);
    const startGanIdx = 시간시작[dayGan];
    const ganIdx = (startGanIdx + jiIdx) % 10;
    return { gan: 천간[ganIdx], ji: 지지[jiIdx], ganIdx, jiIdx };
  }

